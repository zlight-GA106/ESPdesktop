// ========================================
// TFT_eSPI 用户配置文件
// 适用于 ST7735S 128x160 屏幕
// ========================================

// ★★★ 告诉 TFT_eSPI 不要加载库自带的 User_Setup.h ★★★
// 没有这一行，TFT_eSPI 会加载 libraries/TFT_eSPI/User_Setup.h，
// 那个文件里所有驱动都被注释掉了，可能导致配置冲突。
#define USER_SETUP_LOADED

// ==========================================
// 【屏幕选择】
// ==========================================
#define ST7735_DRIVER

// ==========================================
// 【SPI 接口配置】
// ==========================================
#define TFT_MOSI    11    // SPI 数据线
#define TFT_SCLK    12    // SPI 时钟线
#define TFT_CS      14    // 芯片选择
#define TFT_DC      9     // 数据/命令选择
#define TFT_RST     10    // 复位信号

// ==========================================
// 【显示参数】
// ==========================================
#define TFT_WIDTH   128
#define TFT_HEIGHT  160

// ST7735S 方向设置
#define TFT_ROTATION  0   // 0=竖屏(128x160), 1=横屏CW, 2=倒镜(128x160), 3=横屏CCW

// ==========================================
// 【SPI 速率】
// ==========================================
// ⚠️ 关键：ST7735S 在 ESP32-S3 上的稳定性主要取决于 SPI 速率
// 过高的速率会导致：
// - 显示花屏（数据传输错误）
// - 看门狗重启（SPI DMA 卡死）
// - 屏幕初始化失败
//
// 推荐速率（从快到慢）：
// - 10MHz:  最稳定（推荐，特别是有问题时开始这个）
// - 15MHz:  通常稳定
// - 20MHz:  可能有些设备不稳定
// - 40MHz+: 很容易出问题

#define SPI_FREQUENCY  10000000  // 10MHz - 最稳定的频率

// ==========================================
// 【ST7735S 特殊参数】
// ==========================================
// 指定 ST7735S 的初始化表版本
#define ST7735_GREENTAB160x128

// ==========================================
// 【其他字体与功能选项】
// ==========================================
#define LOAD_GLCD           // 加载通用字体
#define LOAD_FONT2          // 加载字体 2
#define LOAD_FONT4          // 加载字体 4
#define LOAD_FONT6
#define LOAD_FONT7
#define LOAD_FONT8

// 平滑字体渲染
#define LOAD_GFXFF

// ==========================================
// 【背光控制】
// ==========================================
#define TFT_BL  13    // 背光控制引脚
#define TFT_BACKLIGHT_ON  HIGH

// ==========================================
// 【PSRAM 配置】(可选，ESP32-S3 有 8MB PSRAM)
// ==========================================
#define USE_PSRAM     // 使用 PSRAM 存储大型缓冲区

// ==========================================
// 【禁用不需要的功能】
// ==========================================
// 禁用 DMA 可能有助于解决某些 SPI 问题
// 取消下面的注释来禁用 DMA
// #define SPI_FREQUENCY  10000000
// 注：TFT_eSPI 默认会尝试使用 DMA，如果有问题可禁用
