#pragma once
#include <Arduino.h>

// ==========================================
// 🤖 AI 客户端接口 (AI Client)
// 职责：处理与云端大语言模型 API 的网络通信与数据解析
// ==========================================

// 初始化 AI 客户端
// [作用]：准备 HTTP 客户端的内部环境与缓冲区。
// [返回值]：初始化成功返回 true。
bool aiBegin();

// 发起 AI 请求 (非阻塞设计)
// [作用]：向云端大模型 API 发送用户的提问文本。为了防止网络延迟导致 MCU 主线程死锁
// （从而引发 UI 冻结或看门狗复位），此接口应设计为快速返回，由后台任务处理实际通信。
// [参数]：text - 用户输入的提问或识别出的文本结果
// [返回值]：成功触发请求返回 true，若网络未连接或当前正忙则返回 false。
bool aiAsk(const String &text);

// 查询 AI 客户端是否正忙
// [作用]：供主循环 (Main Loop) 或 UI 层高频查询。当向云端发出请求并在等待 HTTP 响应，
// 或正在接收分块传输的数据时，此函数返回 true。UI 可据此显示 "请求中 / Thinking..."。
// [返回值]：正在处理网络请求返回 true，处于待机空闲状态返回 false。
bool aiIsBusy();

// 获取最近一次的 AI 回复内容
// [作用]：当 HTTP 请求完成，AI 客户端解析完 JSON 数据后，通过此接口提取完整的回复文本。
// UI 层可将其显示在屏幕的 Label 上。
// [返回值]：返回大模型生成的字符串回复。
String aiGetLastReply();