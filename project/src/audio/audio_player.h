#pragma once
#include <Arduino.h>

// ==========================================
// 🎵 高级音频流与音效播放器接口 (I2S)
// 负责处理：网络电台 (Radio) / AI 语音 (TTS) / UI 点击音效 (click.wav)
// ==========================================

// 初始化音频流媒体引擎与 I2S 总线
// [作用]：分配 I2S DMA 内存，挂载解码器（如 MP3/AAC），准备音频输出通道。
// [返回值]：成功返回 true。
bool audioPlayerBegin();

// 播放指定的网络流媒体 URL
// [作用]：启动持续性音频播放，适用于 RadioPage 的电台地址或 AiPage 的 TTS 音频链接。
// [参数]：url - 包含 "http://" 或 "https://" 的音频流绝对地址。
// [返回值]：成功连接并开始缓冲返回 true。
bool audioPlayerPlayUrl(const String &url);

// 立即中断并停止当前的持续性播放
// [作用]：立刻切断 I2S 数据流并断开网络连接。
// [注意]：根据项目规则，一旦用户离开 RadioPage 或 AiPage，
// ui_manager 必须立刻调用此函数，保证电台或 TTS 被“掐断”，绝不允许后台偷偷发声。
void audioPlayerStop();

// 查询当前是否有持续性音频正在播放
// [返回值]：正在播放流媒体电台或 TTS 时返回 true。
bool audioPlayerIsPlaying();

// 音频流数据泵 (必须在主循环中高频调用)
// [作用]：非阻塞地从网络缓冲区拉取 MP3/AAC 数据，解码并推送到 I2S 硬件。
// 如果此函数在 loop() 中被阻塞，音频会立即出现卡顿、爆音或彻底停播。
void audioPlayerLoop();

// ==========================================
// 【UI 专属音效控制】
// ==========================================

// 播放短暂的界面点击音效 (click.wav)
// [规则强提醒]：
// 1. 根据《ESPdesktop 项目总宪章》，页面自身绝对不能调用此函数！
// 2. 它的触发权严格收归在 `ui_manager` 中，只有当用户按下确认键并引发页面跳转时，
//    才能由管理器统一调用。
// 3. 它的播放优先级极高，不受当前电台或 TTS 的影响，并且必须是极低延迟的。
void audioPlayerPlayClick();