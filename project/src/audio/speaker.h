#pragma once
#include <Arduino.h>

// ==========================================
// 🔊 基础提示音与系统旋律驱动接口 (Speaker)
// ==========================================

// 初始化扬声器发声硬件 (如 PWM 定时器或 I2S 发生器)
// [返回值]：初始化成功返回 true
bool speakerBegin();

// ==========================================
// 【基础短提示音 (Beep)】
// ==========================================

// 触发一次简单的短促提示音
// [参数]：durationMs - 发声持续的毫秒数
// [说明]：可用于报警、按键反馈或系统错误提示
void speakerBeep(int durationMs);

// 强制开启持续发声 (例如长鸣报警)
void speakerOn();

// 强制关闭当前的声音输出
void speakerOff();

// ==========================================
// 【About 页面复古短旋律 (Melody)】
// ==========================================

// 触发播放一段预定义的复古短旋律
// [说明]：调用后立即返回（不阻塞），实际的音符切换由 speakerMelodyLoop 负责
void speakerPlayAboutMelody();

// 旋律播放的非阻塞调度泵
// [说明]：必须放在主程序的 loop() 中高频调用。它会根据时间自动切换音符，
// 直到整段旋律播放完毕后自动停止。
void speakerMelodyLoop();

// 检查当前旋律是否仍在播放中
// [返回值]：正在播放返回 true，播放结束或未启动返回 false。
// [说明]：UI 层可通过此接口判断是否需要阻止其他声音（如 TTS）打断开机音乐。
bool speakerMelodyIsPlaying();