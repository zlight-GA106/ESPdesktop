#pragma once
#include <Arduino.h>

// ==========================================
// 🎤 麦克风采集驱动接口 (INMP441 - I2S)
// 当前阶段目标：环境声音强度检测 (非语音识别)
// ==========================================

// 初始化麦克风 (配置 I2S 总线)
// [作用]：申请 ESP32 的 I2S 资源，配置引脚，并设置采样率（如 16kHz 或 44.1kHz）和 DMA 缓冲区。
// [返回值]：初始化成功返回 true，失败（如 I2S 资源被占满或引脚冲突）返回 false。
bool microphoneBegin();

// 获取原始瞬时采样值 (Raw)
// [说明]：Raw 数据是麦克风在极其微小的瞬间（如几万分之一秒）捕捉到的声波振幅。
// 声音是波，所以 Raw 值会在正数和负数之间疯狂跳动（例如从 -32768 到 +32767）。
// 它是杂乱无章的，直接显示在 UI 上毫无意义，通常只用于底层的数学运算或音频录制。
// [返回值]：瞬时声波振幅。
int microphoneReadRaw();

// 获取处理后的声音强度等级 (Level)
// [说明]：Level 数据是经过一系列数学处理（如均方根 RMS 计算、绝对值求平均、或者对数 dB 转换）
// 并平滑滤波后得到的结果。它代表了人类耳朵真实感知到的“音量大小”。
// 它是一个稳定的正数（例如映射到 0~100 的区间，或者真实的模拟分贝值）。
// 这才是应该传给 app_data.h 并在屏幕上显示的最终业务数据。
// [返回值]：平滑处理后的环境噪音强度（音量）。
int microphoneReadLevel();