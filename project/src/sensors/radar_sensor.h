#pragma once
#include <Arduino.h>

// ==========================================
// 🚶‍♂️ 人体存在雷达驱动接口 (HLK-LD2402 串口型)
// ==========================================

/*
 * [为什么串口型雷达的接口与 GPIO 型不同？]
 * 1. 普通的 GPIO 型雷达（如老式 PIR 或简单微波模块）只输出高低电平（1=有人，0=无人）。
 * 它的接口只需要极其简单的 `bool radarRead()` 去 `digitalRead(PIN)` 即可。
 * 2. 串口型雷达（如 LD2402）不仅能判断有人无人，还能输出距离、运动能量等丰富数据。
 * 它是通过串口源源不断地发送复杂的数据帧（Frame）来实现的。
 * 因此，它的架构必须拆分为三步：
 * - begin: 绑定具体的物理串口。
 * - update: 必须放在主循环(loop)里，非阻塞地把串口缓冲区里的字节“吃掉”并拼装解析。
 * - readPresence: 只是轻量级地读取解析完毕后保存在内存里的标志位，不直接操作硬件。
 */

// 初始化雷达并绑定硬件串口
// [作用]：接收主程序传入的硬件串口实例（如 Serial1），并重置内部解析状态机。
// [参数]：serialPort - ESP32 的硬件串口引用（如 Serial1 或 Serial2）
// [返回值]：初始化成功返回 true
bool radarBegin(HardwareSerial &serialPort);

// 雷达串口数据泵 (必须在 loop() 中高频调用)
// [作用]：非阻塞读取串口缓冲区的数据，按照 LD2402 的帧头(0xF4 0xF3)和帧尾(0xF8 0xF7)进行包解析。
// [返回值]：如果成功解析出一帧完整且有效的新数据，返回 true；否则返回 false。
bool radarUpdate();

// 获取最新的人体存在状态
// [作用]：返回上一帧成功解析出的人体状态。
// [返回值]：true 表示检测到有人或微动，false 表示无人。
bool radarReadPresence();