#pragma once
#include <Arduino.h>

// ==========================================
// 🌡️ 温湿度传感器驱动接口 (SHT40)
// ==========================================

// 初始化温湿度传感器
// [作用]：初始化底层的 I2C 通信，查找总线上的 SHT40 芯片。
// [返回值]：如果成功找到传感器并初始化完成，返回 true；否则返回 false。
bool tempHumiBegin();

// 读取最新的温湿度数据
// [作用]：向传感器发送测量指令，并将读到的真实物理数据填充到传入的变量中。
// [参数]：
//   - temperature: 引用传递，用于接收当前的温度值 (摄氏度)
//   - humidity: 引用传递，用于接收当前的湿度值 (%)
// [返回值]：如果读取成功且数据校验无误，返回 true；如果通信失败，返回 false。
bool tempHumiRead(float &temperature, float &humidity);

// 检查传感器是否仍保持连接
// [作用]：快速验证传感器是否还在 I2C 总线上。常用于主循环中，防止因硬件接线松动导致程序一直卡在读取步骤。
// [返回值]：在线返回 true，掉线返回 false。
bool tempHumiIsConnected();