#pragma once
#include <lvgl.h>

// ==========================================
// 🪟 统一页面外框容器 (UiFrame)
// 职责：标准化所有页面的顶栏、按钮、内容区布局
// ==========================================

/**
 * UiFrame 结构体
 * [说明]：它不是一个真实的LVGL控件类型，而是一个管理一整套相关控件的"句柄打包器"
 * [作用]：创建页面时，将这些经常需要的指针绑定在一起
 */
struct UiFrame {
    // 根容器 (Page Root)
    // [职责]：整个页面的最底层画布，铺满128x160屏幕
    // [生命周期]：删除页面时，只需 lv_obj_del(root) 就能销毁所有子对象
    lv_obj_t *root;

    // 顶栏 - 左侧返回按钮 (Back Button)
    // [显示文本]："返回"
    // [职责]：点击后退回上一级页面
    lv_obj_t *backBtn;

    // 顶栏 - 中间标题文本 (Title Label)
    // [职责]：显示当前页面的名称（如 "Home", "Settings"）
    // [字体]：纯白色，清晰易读
    lv_obj_t *titleLabel;

    // 顶栏 - 右侧菜单按钮 (Menu Button)
    // [显示文本]："菜单"
    // [职责]：点击直接跳回主菜单界面
    lv_obj_t *menuBtn;

    // 顶栏 - 状态栏文本 (Status Label)
    // [显示内容]：系统状态占位符，如 "WiFi:-- MQTT:-- AI:-- Audio:--"
    // [职责]：由ui_manager定时刷新，实时显示系统连接状态
    // [排布]：极其紧凑，靠右对齐，不浪费任何像素
    lv_obj_t *statusLabel;

    // 下方主内容区 (Content Area)
    // [职责]：这是留给子页面的"自留地"
    // [规定]：所有页面内容必须添加到此容器作为子对象，禁止直接添加到root
    // [好处]：内容区可以独立滚动，被顶栏自动裁切保护
    lv_obj_t *content;
};

// ==========================================
// [接口] 创建一个标准外框
// ==========================================
/**
 * @brief 创建标准的Pocket PC风格页面外框
 * 
 * @param title 页面标题（显示在顶栏中间）
 * @return UiFrame 包含所有关键控件指针的结构体
 */
UiFrame uiFrameCreate(const char *title);
